"""Convert a PNG to a 1-bit C header for the firmware.

Usage:
  python scripts/convert_mono_image.py input.png output.h name
      [--nine-slice LEFT TOP RIGHT BOTTOM] [--cover LEFT TOP RIGHT BOTTOM]

--nine-slice gives the corner sizes in pixels; the edges and center between
them are tiled, so every layer must already have started inside the corners or
it breaks up where the middle repeats. --cover places the cover inside a
9-slice frame: its distance from each image edge. Without either option the
image is a plain pattern tile. Grays are Floyd-Steinberg dithered;
transparency becomes white.
"""

import argparse
import os

from PIL import Image


def main():
    parser = argparse.ArgumentParser(description='Convert a PNG to a 1-bit C header.')
    parser.add_argument('input')
    parser.add_argument('output')
    parser.add_argument('name', help='C++ namespace for the image')
    parser.add_argument('--nine-slice', nargs=4, type=int, metavar=('LEFT', 'TOP', 'RIGHT', 'BOTTOM'))
    parser.add_argument('--cover', nargs=4, type=int, metavar=('LEFT', 'TOP', 'RIGHT', 'BOTTOM'))
    args = parser.parse_args()

    img = Image.open(args.input).convert('RGBA')
    background = Image.new('RGBA', img.size, (255, 255, 255, 255))
    background.paste(img, mask=img.split()[3])
    img = background.convert('L').convert('1')  # dithers grays
    width, height = img.size
    if args.nine_slice:
        left, top, right, bottom = args.nine_slice
        if left + right >= width or top + bottom >= height:
            parser.error('slices leave no tiled middle')

    row_bytes = (width + 7) // 8
    packed = []
    for y in range(height):
        for x in range(0, width, 8):
            byte = 0
            for b in range(8):
                # 1 for white, 0 for black (same as the icon headers)
                if x + b >= width or img.getpixel((x + b, y)):
                    byte |= 1 << (7 - b)
            packed.append(byte)

    out = ['#pragma once', '#include <cstdint>', '',
           f'// Generated by scripts/convert_mono_image.py from {os.path.basename(args.input)}.',
           f'namespace {args.name} {{', '',
           f'constexpr int kWidth = {width};', f'constexpr int kHeight = {height};',
           f'constexpr int kRowBytes = {row_bytes};']
    if args.nine_slice:
        out += [f'constexpr int kSlice{side} = {v};'
                for side, v in zip(('Left', 'Top', 'Right', 'Bottom'), args.nine_slice)]
    if args.cover:
        out += [f'constexpr int kCover{side} = {v};' for side, v in zip(('Left', 'Top', 'Right', 'Bottom'), args.cover)]
    out += ['', '// Row-major, MSB first; 1 = white, 0 = black.', 'static const uint8_t kPixels[] = {']
    for i in range(0, len(packed), 16):
        out.append('    ' + ', '.join(f'0x{v:02X}' for v in packed[i:i + 16]) + ',')
    out += ['};', '',
            'inline bool isBlack(const int x, const int y) {',
            '  return !(kPixels[y * kRowBytes + (x >> 3)] & (0x80 >> (x & 7)));',
            '}', '', f'}}  // namespace {args.name}', '']
    with open(args.output, 'w') as f:
        f.write('\n'.join(out))
    print(f'Wrote {args.output} ({width}x{height})')


if __name__ == '__main__':
    main()
